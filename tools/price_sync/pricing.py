# -*- coding: utf-8 -*-
"""Правила ценообразования СплитХаб.

Цена витрины = закупка поставщика + наценка источника, округлённая ВВЕРХ.
Наценки заданы владельцем: трио.рус +5%, остальные поставщики +10%.

Шаг округления зависит от суммы: дорогие позиции идут до …90, а дешёвый расходник —
до 5 ₽. Иначе шаг в сотню съедает смысл наценки: болт с закупкой 185 ₽ после +10%
стоил бы 290 ₽ вместо 205 ₽, то есть наценка выходила бы 57%, а не 10%.
"""
from __future__ import annotations

import math

#: Наценка по источнику (доля, не проценты).
MARKUP = {
    "trio": 0.05,
    "trio_rashod": 0.10,   # расходники у трио берём с наценкой 10%, не 5%
    "trio_krepezh": 1.00,  # дюбели, болты, гайки с прессшайбой у трио — наценка 100%
    "techno": 0.10,   # ТЕХНОСИСТЕМС: +10% от БОЛЬШЕЙ цены прайса
    "jac": 0.10,
    "oasis": 0.10,
}


#: Ниже этой суммы округляем мелким шагом, выше — до …90.
CHEAP_LIMIT = 1000

#: Шаг округления для дешёвых позиций.
CHEAP_STEP = 5


def _kopecks(raw: float) -> float:
    """Отсечь мусор плавающей точки: 900 * 1.1 даёт 990.0000000000001, и цена
    уезжает на шаг вверх. Деньги считаем с точностью до копейки."""
    return round(raw, 2)


def round_up_5(raw: float) -> int:
    """Округлить ВВЕРХ до ближайших 5 ₽: 99 → 100, 203,5 → 205, 187 → 190."""
    return int(math.ceil(_kopecks(raw) / CHEAP_STEP) * CHEAP_STEP)


def round_up_90(raw: float) -> int:
    """Округлить ВВЕРХ до ближайшего числа, оканчивающегося на …90.

    275 → 290, 15 692 → 15 790, 23 562 → 23 590, 14 990 → 14 990.
    """
    raw = _kopecks(raw)
    base = (int(raw) // 100) * 100
    return base + 90 if raw <= base + 90 else base + 190


def compute_price(cost: float, source: str) -> int:
    """Цена витрины из закупочной цены поставщика."""
    if cost is None or cost <= 0:
        raise ValueError("закупочная цена должна быть больше нуля")
    if source not in MARKUP:
        raise ValueError("неизвестный источник: " + source)
    raw = _kopecks(cost * (1 + MARKUP[source]))
    return round_up_5(raw) if raw < CHEAP_LIMIT else round_up_90(raw)
